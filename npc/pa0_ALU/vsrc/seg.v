`timescale 1ns/1ps

module seg(
  input  [3:0] b,
  output reg [7:0] h
); 

always @(*) begin
  	case(b)
      'd0 : h = 8'b00000010;//0
      'd1 : h = 8'b10011111;//1
      'd2 : h = 8'b00100101;//2
      'd3 : h = 8'b00001101;//3
      'd4 : h = 8'b10011001;//4
      'd5 : h = 8'b01001001;//5
      'd6 : h = 8'b01000001;//6
      'd7 : h = 8'b00011111;//7
      'd8 : h = 8'b00000000;//8
      'd9 : h = 8'b00001001;//9

      // 'd10: h = 8'b00010001;//a
      // 'd11: h = 8'b11000001;//b
      'd11: h = 8'b11111101;//-
      'd10: h = 8'b11111111;//+

      'd12: h = 8'b01100011;//c
      'd13: h = 8'b10000101;//d
      'd14: h = 8'b01100001;//e
      'd15: h = 8'b01110001;//f
      default : h = 8'b11111111;//an
    endcase
end
endmodule
